function GetRequiredTable(ScatID, code, Cid) {
  let dt = null;
  let dr = null;
  code = String(code);
  code = code.substring(code.indexOf('-') + 1).toLowerCase();
  const scatTables = { 'engine-size': Engin_Size, ops: Operating_System, scsize: Screen_Size, breed: Breed };
  for (const key of Object.keys(scatTables)) {
    if (code === key) {
      dr = select(scatTables[key](), 'SCATID', ScatID);
      if (dr.length > 0) {
        dt = copyToDataTable(dr);
      } else {
        dt = []; // empty table with columns ID, SCATID, Title
      }
    }
  }
  if (code === 'mother-tongue') {
    dr = select(Mother_Tongue(), 'CID', Cid);
    if (dr.length === 0) {
      dr = Mother_Tongue();
    }
    dt = copyToDataTable(dr);
  }
  if (code === 'community') {
    dr = select(Community(), 'CID', Cid);
    if (dr.length === 0) {
      dr = Community();
    }
    dt = copyToDataTable(dr);
  }
  return dt;
}

