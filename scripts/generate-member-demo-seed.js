// ---------- SQL literal helpers ----------
const lit = (v) => {
  if (v === null || v === undefined) return 'NULL';
  if (typeof v === 'number') return Number.isFinite(v) ? String(v) : 'NULL';
  if (typeof v === 'boolean') return v ? 'true' : 'false';
  if (v instanceof Date) return `'${v.toISOString().replace('T', ' ').slice(0, 19)}'`;
  if (typeof v === 'object' && v.raw) return v.raw;
  return `'${String(v).replace(/'/g, "''")}'`;
};
const raw = (s) => ({ raw: s });
function insert(table, rows, { overriding = false } = {}) {
  if (!rows.length) return '';
  const cols = Object.keys(rows[0]);
  const values = rows.map((r) => `  (${cols.map((c) => lit(r[c])).join(', ')})`).join(',\n');
  return `insert into public.${table} (${cols.join(', ')})${overriding ? ' overriding system value' : ''} values\n${values};\n`;
}
const daysAgo = (d, h = 10) => { const t = new Date(Date.now() - d * 86400000); t.setHours(h, 15, 0, 0); return t; };
const ddmmyyyy = (d) => `${String(d.getDate()).padStart(2, '0')}-${String(d.getMonth() + 1).padStart(2, '0')}-${d.getFullYear()}`;

// ---------- schema repair (copied from db_shopping.dbo) ----------
async function tableDef(client, schema, table) {
  const r = await client.query(`
    select a.attname as col, format_type(a.atttypid, a.atttypmod) as type, a.attnotnull as notnull, a.attidentity as ident
    from pg_attribute a join pg_class c on c.oid = a.attrelid join pg_namespace n on n.oid = c.relnamespace
    where n.nspname = $1 and c.relname = $2 and a.attnum > 0 and not a.attisdropped order by a.attnum`, [schema, table]);
  return r.rows;
}
const colSql = (c) => `"${c.col}" ${c.type}${c.ident ? ' generated by default as identity' : ''}${c.notnull && !c.ident ? ' not null' : ''}`;

async function schemaRepair(aff, shop) {
  const out = ['-- ===== 1. Schema repair (additive only: create missing tables, add missing columns) =====\n'];
  const existing = new Set((await aff.query("select table_name from information_schema.tables where table_schema = 'public'")).rows.map((r) => r.table_name));

  for (const t of ['member_master', 'tbl_incomedistribution', 'portal_master']) {
    const def = await tableDef(shop, 'dbo', t);
    if (!def.length) throw new Error(`db_shopping.dbo.${t} not found; cannot copy its definition`);
    out.push(`-- ${t}: ${existing.has(t) ? 'exists' : 'missing in db_affiliate'}; definition copied from db_shopping.dbo.${t}`);
    out.push(`create table if not exists public.${t} (\n  ${def.map(colSql).join(',\n  ')}\n);\n`);
  }
  // city: in neither database. Conversion-file definition with ctid renamed to ctid_col (same convention as db_shopping).
  out.push('-- city: missing everywhere ("ctid" is a reserved system column); ctid renamed to ctid_col as in db_shopping');
  out.push('create table if not exists public.city (\n  ctid_col integer primary key,\n  cid integer,\n  sid integer not null,\n  cityname varchar(250) not null,\n  active boolean\n);\n');

  // portal_login: only "plid" was migrated. Add every column of the db_shopping copy that is missing.
  const have = new Set((await aff.query("select column_name from information_schema.columns where table_schema = 'public' and table_name = 'portal_login'")).rows.map((r) => r.column_name));
  const add = (await tableDef(shop, 'dbo', 'portal_login')).filter((c) => !have.has(c.col));
  out.push(`-- portal_login: adding ${add.length} missing columns from db_shopping.dbo.portal_login`);
  for (const c of add) out.push(`alter table public.portal_login add column if not exists "${c.col}" ${c.type};`);
  out.push('');
  return out.join('\n');
}

